def sub1(text, old, new, what):
    n = text.count(old)
    if n != 1:
        die("%s: anchor occurs %d times: %r" % (what, n, old[:80]))
    return text.replace(old, new)


def span(text, start, end, new, what):
    if text.count(start) != 1 or text.count(end) != 1:
        die("%s: span anchors not unique (%d, %d)" % (what, text.count(start), text.count(end)))
    i, j = text.index(start), text.index(end)
    if j <= i:
        die(what + ": span end precedes start")
    return text[:i] + new + text[j:]


def line_starting(text, prefix, new, what):
    hits = [ln for ln in text.split("\n") if ln.startswith(prefix)]
    if len(hits) != 1:
        die("%s: %d lines start with %r" % (what, len(hits), prefix))
    return text.replace(hits[0], new)


def order_range(t):
    return t.split("\n## THE ORDER\n", 1)[1].split("\n## ARCHIVED", 1)[0]


def published_range(t):
    """What the published sed command reads: from the `## THE ORDER` line THROUGH the `## ARCHIVED`
    heading line, inclusive. S113's first assembly checked the narrower split above, and a closed id
    written in the ARCHIVED heading made the published second scan print one more than the assembler's."""
    i = t.index("\n## THE ORDER\n") + 1
    j = t.index("\n## ARCHIVED", i) + 1
    k = t.index("\n", j)
    return t[i:k + 1]


def scans(t):
    r = published_range(t)
    bold = set(m[2:] for m in re.findall(r"\*\*[0-9]+\.[0-9]+", r))
    anyd = set(re.findall(r"[0-9]+\.[0-9]+", r))
    root5 = set(i for i in bold if i.split(".")[0] == "5")
    return bold, anyd, len(root5)


def graveyard_md5(t):
    lines, on, out = t.split("\n"), False, []
    for ln in lines:
        if not on and re.match(r"^## .*GRAVEYARD", ln):
            on = True
        if on:
            out.append(ln)
            if ln.startswith("<!-- GRAVEYARD-END -->"):
                break
    return hashlib.md5(("\n".join(out) + "\n").encode("utf-8")).hexdigest()


