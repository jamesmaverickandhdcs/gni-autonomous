# --------------------------------------------------------------------------- io

def norm_md5(raw: bytes) -> str:
    """R-S98-3: hash what the content IS, not how git handed it over."""
    if raw.startswith(b"\xef\xbb\xbf"):
        raw = raw[3:]
    return hashlib.md5(raw.replace(b"\r\n", b"\n")).hexdigest()


def decode(raw: bytes) -> str:
    """utf-8-sig: six files under ai_engine/ carry a BOM and ast.parse dies on it."""
    return raw.decode("utf-8-sig", "replace")


def sh(args: list[str], cwd: Path | None = None) -> tuple[int, str]:
    try:
        p = subprocess.run(args, cwd=str(cwd or ROOT), capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=120)
        return p.returncode, p.stdout or ""
    except Exception as exc:                                       # noqa: BLE001
        return 1, "<%s: %s>" % (type(exc).__name__, exc)


def tracked_py(root: Path) -> list[Path]:
    """Tracked *.py only. `git ls-files` is deterministic on an unchanged tree, and it
    excludes the venv, build output and anything untracked -- none of which is architecture."""
    rc, out = sh(["git", "ls-files", "*.py"], cwd=root)
    if rc != 0:
        return []
    return [root / line.strip() for line in out.splitlines() if line.strip()]


# --------------------------------------------------------------------------- naming

def sys_path_sites(tree: ast.AST) -> int:
    """Count `sys.path.append(...)` / `sys.path.insert(...)` calls.

    These are why a module has more than one name. `ai_engine/mad_runner.py` does
    `sys.path.append(dirname(__file__))`, which makes `ai_engine/` a path root, so its
    siblings address each other as `from quota_guard import ...` and its subpackages as
    `from analysis.mad_protocol import ...` -- never as `ai_engine.quota_guard`. A resolver
    that knows only the package-relative name matches NONE of those and reports an almost
    edgeless graph. That is exactly what this generator's first run did."""
    n = 0
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) \
                and node.func.attr in ("append", "insert") \
                and isinstance(node.func.value, ast.Attribute) \
                and node.func.value.attr == "path" \
                and isinstance(node.func.value.value, ast.Name) \
                and node.func.value.value.id == "sys":
            n += 1
    return n


def aliases_of(path: Path, roots: list[Path]) -> set[str]:
    """Every dotted name this file answers to, one per path root it sits under.

    Roots are DERIVED, not listed: the repo root, plus every directory holding a tracked
    `*.py`, because Python puts the entry script's own directory on `sys.path` and this tree
    additionally appends parents by hand. `ai_engine/analysis/mad_protocol.py` therefore
    answers to `ai_engine.analysis.mad_protocol`, `analysis.mad_protocol` AND `mad_protocol`,
    and which one a given import uses depends on who is running."""
    out: set[str] = set()
    for r in roots:
        try:
            rel = path.relative_to(r)
        except ValueError:
            continue
        parts = list(rel.parts)
        if parts[-1] == "__init__.py":
            parts = parts[:-1]
        else:
            parts[-1] = parts[-1][:-3]
        if parts:
            out.add(".".join(parts))
    return out


def module_name(path: Path, root: Path) -> str:
    """Dotted module name, derived by walking up while __init__.py exists.

    ai_engine/analysis/foo.py -> ai_engine.analysis.foo   (ai_engine/ is a package)
    tools/gni_state.py        -> gni_state                (tools/ is not)
    dryrun_x.py               -> dryrun_x
    """
    rel = path.relative_to(root)
    parts = list(rel.parts)
    stem = parts[-1][:-3] if parts[-1].endswith(".py") else parts[-1]
    pkg: list[str] = []
    d = path.parent
    while d != root and (d / "__init__.py").is_file():
        pkg.insert(0, d.name)
        d = d.parent
    if stem == "__init__":
        return ".".join(pkg) if pkg else "__init__"
    return ".".join(pkg + [stem])


# --------------------------------------------------------------------------- ast

def imports_of(tree: ast.AST) -> tuple[list[list[str]], set[str]]:
    """Return (chains, relative_forms).

    Each BINDING produces one CHAIN of candidate dotted names, longest first. The caller
    resolves a chain to AT MOST ONE edge -- the longest candidate that names a real module.

    Chains, not a pooled set, because pooling loses which candidate came from which
    statement: `from pkg import alpha` would then yield edges to BOTH `pkg` and `pkg.alpha`,
    every package `__init__.py` would look heavily imported, and no package could ever appear
    as unreferenced. The control probe caught exactly that on this file's first run.

    `from X import y` is genuinely ambiguous in the AST -- `y` may be a submodule or a symbol
    -- so the chain is [X.y, X] and the real module set decides, which is the only thing that
    can. `relative_forms` holds any `from .x import y`; this tree contains none today, and if
    one ever appears the caller REFUSES rather than resolving it wrongly.
    """
    chains: list[list[str]] = []
    relative: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                parts = a.name.split(".")
                chains.append([".".join(parts[:i]) for i in range(len(parts), 0, -1)])
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                relative.add("." * node.level + (node.module or ""))
                continue
            if not node.module:
                continue
            for a in node.names:
                chains.append([node.module + "." + a.name, node.module])
    return chains, relative


def module_symbols(tree: ast.Module) -> set[str]:
    """Module-level definitions only: def, async def, class, and plain NAME = ... .
    Underscore names are KEPT -- `_FORCE_PROVIDER` is precisely the class of symbol this
    section exists to surface. Dunders are kept too and flagged at render time."""
    out: set[str] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            out.add(node.name)
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    out.add(t.id)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            out.add(node.target.id)
    return out


def referenced_names(tree: ast.AST) -> set[str]:
    """Every name READ and every attribute label read anywhere in the module.

    LOAD CONTEXT ONLY. `_FORCE_PROVIDER = None` creates an ast.Name for the target in STORE
    context, and counting that as a reference would make every constant look used by its own
    definition -- which silently empties the one table this section exists to fill.

    Attributes are included because `mod.SYMBOL` is how a symbol crosses a module boundary.
    This over-collects across modules on purpose: a false NEGATIVE for dead code is the safe
    direction, and the over-collection is disclosed in 5.6."""
    out: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load):
            out.add(node.id)
        elif isinstance(node, ast.Attribute) and isinstance(node.ctx, ast.Load):
            out.add(node.attr)
    return out


# --------------------------------------------------------------------------- collect

def collect(root: Path) -> dict:
    """Parse every tracked *.py once. Raises ValueError -- never returns a partial map --
    when a source will not parse or two files claim one module name."""
    paths = tracked_py(root)
    if not paths:
        raise ValueError("`git ls-files '*.py'` returned nothing under %s" % root)
    roots = sorted({root} | {p.parent for p in paths}, key=lambda p: len(p.parts))
    mods: dict[str, dict] = {}
    clashes: list[str] = []
    manifest: list[str] = []
    for path in sorted(paths):
        if not path.is_file():
            raise ValueError("tracked but absent from the working tree: %s" % path)
        raw = path.read_bytes()
        name = module_name(path, root)
        try:
            tree = ast.parse(decode(raw), filename=str(path))
        except SyntaxError as exc:
            raise ValueError("%s will not parse: %s" % (path, exc))
        if name in mods:
            clashes.append("%s claimed by %s and %s"
                           % (name, mods[name]["rel"], path.relative_to(root).as_posix()))
            continue
        chains, rel_forms = imports_of(tree)
        mods[name] = {
            "rel": path.relative_to(root).as_posix(),
            "chains": chains,
            "relative": rel_forms,
            "symbols": module_symbols(tree),
            "refs": referenced_names(tree),
            "aliases": aliases_of(path, roots),
            "path_sites": sys_path_sites(tree),
        }
        manifest.append("%s\0%s" % (path.relative_to(root).as_posix(), norm_md5(raw)))
    if clashes:
        raise ValueError("module name collision -- " + "; ".join(sorted(clashes)))
    rc, head = sh(["git", "rev-parse", "--short", "HEAD"], cwd=root)
    return {
        "modules": mods,
        "roots": [r.relative_to(root).as_posix() or "." for r in roots],
        "head": head.strip() or "unknown",
        "manifest_md5": norm_md5(("\n".join(sorted(manifest)) + "\n").encode("utf-8")),
    }


# --------------------------------------------------------------------------- analyse

def resolve(target: str, known: set[str]) -> str | None:
    """Longest-prefix resolution of an import target against the real module set.
    `ai_engine.analysis.foo.bar` resolves to `ai_engine.analysis.foo` when that module
    exists. A target matching nothing is EXTERNAL -- stdlib or third party -- and this
    function deliberately does not try to say which: distinguishing them needs a
    hand-written list, and a hand-written list is the thing C5 forbids."""
    parts = target.split(".")
    for i in range(len(parts), 0, -1):
        cand = ".".join(parts[:i])
        if cand in known:
            return cand
    return None


def analyse(snap: dict) -> dict:
    """Everything published is derived here. No threshold is hand-written."""
    mods = snap["modules"]
    known = set(mods)
    if not known:
        raise ValueError("no module survived collection")

    stray = {n: sorted(v["relative"]) for n, v in mods.items() if v["relative"]}
    if stray:
        raise ValueError(
            "relative imports found and this resolver does not handle them: "
            + "; ".join("%s -> %s" % (n, ",".join(f)) for n, f in sorted(stray.items())))

    # ALIAS MAP. A name may be claimed by more than one file once the tree's own path roots
    # are taken into account. An ambiguous alias produces NO edge and is COUNTED, because a
    # coin-flip between two real modules is worse than a gap that says so.
    alias_map: dict[str, set[str]] = {}
    for name, v in mods.items():
        for al in v["aliases"]:
            alias_map.setdefault(al, set()).add(name)
    ambiguous = {al: sorted(owners) for al, owners in alias_map.items() if len(owners) > 1}

    edges: dict[str, set[str]] = {n: set() for n in known}
    external: dict[str, set[str]] = {n: set() for n in known}
    unresolved_ambiguous = 0
    for name, v in mods.items():
        for chain in v["chains"]:
            hit = None
            stop = False
            for cand in chain:                      # longest first
                owners = alias_map.get(cand)
                if not owners:
                    continue
                if len(owners) > 1:
                    unresolved_ambiguous += 1
                    stop = True
                    break
                hit = next(iter(owners))
                break
            if stop:
                continue
            if hit is None:
                external[name].add(chain[-1].split(".")[0])
            elif hit != name:
                edges[name].add(hit)

    imported_by: dict[str, set[str]] = {n: set() for n in known}
    for src, dsts in edges.items():
        for d in dsts:
            imported_by[d].add(src)

    is_test = {n: ("tests/" in v["rel"] or v["rel"].startswith("tests/"))
               for n, v in mods.items()}
    covered = {n for n in known
               if any(is_test[s] for s in imported_by[n])}

    # A package `__init__.py` is EXECUTED whenever any submodule of it is imported, so
    # "nothing imports it" is false for a package by construction. Excluded by an exact
    # rule, not by a heuristic, and the exclusion is stated in the rendered prose.
    is_package = {n: v["rel"].endswith("__init__.py") for n, v in mods.items()}
    unreferenced_modules = sorted(
        n for n in known
        if not imported_by[n] and not is_test[n] and not is_package[n])

    # SYMBOLS. A symbol is "referenced elsewhere" when its name appears in ANY other
    # module's name/attribute set. Same-name collisions across modules therefore mask a
    # dead symbol -- a FALSE NEGATIVE, which is the safe direction, and it is disclosed.
    refs_by_other: dict[str, set[str]] = {}
    for name, v in mods.items():
        for r in v["refs"]:
            refs_by_other.setdefault(r, set()).add(name)
    lonely: dict[str, list[str]] = {}
    internal_only: dict[str, list[str]] = {}
    n_symbols = 0
    for name, v in mods.items():
        for s in sorted(v["symbols"]):
            if DUNDER_RE.match(s):
                continue
            n_symbols += 1
            users = refs_by_other.get(s, set())
            if not users:
                lonely.setdefault(name, []).append(s)
            elif users == {name}:
                internal_only.setdefault(name, []).append(s)

    pkg_of = {}
    for n, v in mods.items():
        rel = v["rel"]
        pkg_of[n] = rel.rsplit("/", 1)[0] if "/" in rel else "(repo root)"
    packages: dict[str, list[str]] = {}
    for n, p in pkg_of.items():
        packages.setdefault(p, []).append(n)

    return {
        "edges": edges, "external": external, "imported_by": imported_by,
        "is_test": is_test, "covered": covered, "packages": packages,
        "unreferenced_modules": unreferenced_modules, "lonely": lonely,
        "internal_only": internal_only, "is_package": is_package,
        "n_symbols": n_symbols, "pkg_of": pkg_of,
        "ambiguous": ambiguous, "unresolved_ambiguous": unresolved_ambiguous,
    }


