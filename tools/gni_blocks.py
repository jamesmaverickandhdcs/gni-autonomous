def control_probe() -> tuple[list[str], int]:
    """Assert the instrument's expectations against synthetic sources with KNOWN answers,
    before one real file is read. The count is COUNTED, never written down: C5 / R-S81-5
    forbids a check holding a hand-written expected integer, and `gni_state.py` line 323
    still prints a literal that is only accidentally correct."""
    import tempfile

    fails: list[str] = []
    n = 0

    # --- module naming, including the case this repo actually has both of -------------
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        for rel, body in PROBE_SOURCES.items():
            p = root / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(body, encoding="utf-8")
        cases = [
            ("ai_engine/mad_runner.py", "ai_engine.mad_runner", "canonical, repo-root name"),
            ("tools/gni_macro_map.py", "gni_macro_map",
             "NEGATIVE: tools/ has no __init__.py, so no package prefix"),
            ("ai_engine/__init__.py", "ai_engine", "the package itself"),
        ]
        for rel, want, label in cases:
            n += 1
            got = module_name(root / rel, root)
            if got != want:
                fails.append("%s: %s -> %r, expected %r" % (label, rel, got, want))

        # --- one file, several names, because the tree appends its own roots -------------
        n += 1
        al = aliases_of(root / "ai_engine/analysis/mad_protocol.py",
                        [root, root / "ai_engine", root / "ai_engine/analysis"])
        if not {"ai_engine.analysis.mad_protocol", "analysis.mad_protocol",
                "mad_protocol"} <= al:
            fails.append("aliases_of missed a real name for mad_protocol: %r" % (sorted(al),))

        # --- BOM: the trap gni_rule_checks.py documented at its line 66 ---------------
        n += 1
        try:
            ast.parse(decode(b"\xef\xbb\xbfx = 1\n"))
        except SyntaxError:
            fails.append("decode() does not strip the BOM; ast.parse dies on six real files")
        n += 1
        try:
            ast.parse("\ufeffx = 1\n")
            fails.append("the probe itself is wrong: a raw BOM was supposed to break ast.parse")
        except SyntaxError:
            pass

        # --- the whole graph, end to end, against known answers -----------------------
        sh(["git", "init", "-q"], cwd=root)
        sh(["git", "add", "-A"], cwd=root)
        sh(["git", "-c", "user.email=p@p", "-c", "user.name=p", "commit", "-qm", "p"], cwd=root)
        try:
            snap = collect(root)
            a = analyse(snap)
        except ValueError as exc:
            return fails + ["collect/analyse refused the probe tree: %s" % exc], n + 1

        mr = a["edges"].get("ai_engine.mad_runner", set())
        n += 1
        if "ai_engine.quota_guard" not in mr:
            fails.append("`from quota_guard import ...` (sibling, via the appended root) "
                         "must resolve; got %r" % (sorted(mr),))
        n += 1
        if "ai_engine.analysis.mad_protocol" not in mr:
            fails.append("a FUNCTION-LEVEL `from analysis.mad_protocol import ...` must "
                         "resolve; got %r" % (sorted(mr),))
        n += 1
        if a["edges"].get("ai_engine.tests.test_groq_guardian") != {"ai_engine.groq_guardian"}:
            fails.append("a test importing a sibling by bare name must resolve; got %r"
                         % (a["edges"].get("ai_engine.tests.test_groq_guardian"),))
        n += 1
        if not a["covered"] & {"ai_engine.groq_guardian"}:
            fails.append("test coverage must be non-empty when a test imports a module")
        n += 1
        if a["edges"].get("gni_rule_checks") != {"gni_macro_map"}:
            fails.append("bare-name import inside tools/ must resolve; got %r"
                         % (a["edges"].get("gni_rule_checks"),))

        ext = a["external"].get("ai_engine.mad_runner", set())
        n += 1
        if not {"os", "sys", "dotenv"} <= ext:
            fails.append("stdlib/third-party must land in `external`, got %r" % (sorted(ext),))
        n += 1
        if {"os", "sys", "dotenv"} & mr:
            fails.append("NEGATIVE: an external import must NOT become an internal edge")

        # --- ambiguity is COUNTED, never guessed -----------------------------------------
        n += 1
        if "helper" not in a["ambiguous"]:
            fails.append("two files answering to `helper` must be recorded as ambiguous")
        n += 1
        if len(a["ambiguous"].get("helper", [])) != 2:
            fails.append("the ambiguous alias must name BOTH owners")

        # --- path-root sites ---------------------------------------------------------------
        n += 1
        if snap["modules"]["ai_engine.mad_runner"]["path_sites"] != 1:
            fails.append("sys.path.append must be counted where it exists")
        n += 1
        if snap["modules"]["ai_engine.quota_guard"]["path_sites"] != 0:
            fails.append("NEGATIVE: a module with no sys.path call must count zero")

        # --- orphan + symbols --------------------------------------------------------------
        n += 1
        if "ai_engine.analysis.orphan_module" not in a["unreferenced_modules"]:
            fails.append("a module nothing imports must be listed, got %r"
                         % (a["unreferenced_modules"],))
        n += 1
        if "ai_engine.quota_guard" in a["unreferenced_modules"]:
            fails.append("NEGATIVE: quota_guard IS imported and must not be listed")
        n += 1
        if "ai_engine" in a["unreferenced_modules"]:
            fails.append("NEGATIVE: a package __init__ is executed by any submodule import")

        lon = a["lonely"].get("ai_engine.analysis.mad_protocol", [])
        n += 1
        if "NEVER_READ_ANYWHERE" not in lon:
            fails.append("a symbol read nowhere must be listed, got %r" % (lon,))
        n += 1
        if "PRIVATE_SEED" in lon:
            fails.append("NEGATIVE: PRIVATE_SEED is read inside its own module")
        n += 1
        if "run_mad_protocol" in lon:
            fails.append("NEGATIVE: run_mad_protocol is read by mad_runner")

    # --- resolution, isolated ----------------------------------------------------------
    known = {"a.b", "a.b.c"}
    n += 1
    if resolve("a.b.c.d", known) != "a.b.c":
        fails.append("resolve() must take the LONGEST matching prefix")
    n += 1
    if resolve("zzz", known) is not None:
        fails.append("NEGATIVE: an unknown target must resolve to None, not to a guess")

    # --- relative imports must REFUSE, not resolve wrongly ------------------------------
    n += 1
    tgts, rel_forms = imports_of(ast.parse("from . import x\n"))
    if not rel_forms:
        fails.append("a relative import must be reported so analyse() can refuse")

    # --- hashing -----------------------------------------------------------------------
    n += 1
    if norm_md5(b"a\r\nb\r\n") != norm_md5(b"a\nb\n"):
        fails.append("norm_md5 is not EOL-invariant (R-S98-3)")
    n += 1
    if norm_md5(b"\xef\xbb\xbfa\n") != norm_md5(b"a\n"):
        fails.append("norm_md5 does not strip the BOM (R-S98-3)")
    n += 1
    if norm_md5(b"a\n") == norm_md5(b"b\n"):
        fails.append("NEGATIVE: norm_md5 must distinguish different content")
    return fails, n


# --------------------------------------------------------------------------- render

def render(snap: dict, a: dict) -> str:
    mods = snap["modules"]
    o: list[str] = []
    o.append("## §5 BUILDING BLOCK VIEW — **GENERATED**")
    o.append("")
    o.append("**GENERATED by `tools/gni_blocks.py` from the AST of %d tracked `*.py` at HEAD "
             "`%s` — source manifest md5 `%s` (EOL-normalised, R-S98-3). This section carries "
             "NO clock of its own: re-running it on an unchanged tree reproduces these bytes "
             "exactly. Do not hand-edit — the next run overwrites it. If this section is "
             "absent, the generator failed and that absence is the signal.**"
             % (len(mods), snap["head"], snap["manifest_md5"]))
    o.append("")
    o.append("**Section 5 is what is WRITTEN. Section 6 is what ACTUALLY RAN; section 7 is what "
             "is DECLARED. Whether a workflow invokes a module directly is §7.1's entrypoint "
             "column, not this section's — see 5.6.**")
    o.append("")

    # 5.1 ------------------------------------------------------------------
    o.append("### 5.0 The path roots this tree creates for itself")
    o.append("")
    sites = sorted(((v["path_sites"], n) for n, v in mods.items() if v["path_sites"]),
                   reverse=True)
    o.append("**%d modules call `sys.path.append` or `sys.path.insert`, %d calls in total.** "
             "This is not a footnote: it is why a single file answers to several names. "
             "`ai_engine/mad_runner.py` puts its own directory on the path, so its siblings "
             "import each other as `from quota_guard import ...` and its subpackages as "
             "`from analysis.mad_protocol import ...` — never by the `ai_engine.` prefix a "
             "package-relative reader would expect. Every name below is resolved against "
             "every root the tree creates, and a name claimed by two files produces NO edge."
             % (len(sites), sum(k for k, _ in sites)))
    o.append("")
    if sites:
        o.append("| module | `sys.path` calls |")
        o.append("|---|---|")
        for k, n_ in sites:
            o.append("| `%s` | %d |" % (n_, k))
        o.append("")
    amb = a["ambiguous"]
    o.append("**Ambiguous names: %d.** %s"
             % (len(amb),
                "An import naming one of these could mean either file, so this generator "
                "records it and creates no edge — %d import statements were dropped that way."
                % a["unresolved_ambiguous"] if amb else "No name is claimed by two files."))
    if amb:
        o.append("")
        o.append("| name | claimed by |")
        o.append("|---|---|")
        for al in sorted(amb):
            o.append("| `%s` | %s |" % (al, ", ".join("`%s`" % x for x in amb[al])))
    o.append("")
    o.append("### 5.1 Module inventory by package")
    o.append("")
    o.append("| package | modules | internal imports out | imported by |")
    o.append("|---|---|---|---|")
    for pkg in sorted(a["packages"]):
        names = a["packages"][pkg]
        out_e = sum(len(a["edges"][n]) for n in names)
        in_e = sum(len(a["imported_by"][n]) for n in names)
        o.append("| `%s` | %d | %d | %d |" % (pkg, len(names), out_e, in_e))
    o.append("")

    # 5.2 ------------------------------------------------------------------
    o.append("### 5.2 What each module imports, and who imports it")
    o.append("")
    o.append("Internal edges only. An import that resolves to no module in the tree is "
             "EXTERNAL and counted in the last column; this generator deliberately does not "
             "split stdlib from third-party, because doing so needs a hand-written list and a "
             "hand-written list is what C5 forbids.")
    o.append("")
    o.append("| module | file | imports (internal) | imported by | external |")
    o.append("|---|---|---|---|---|")
    for name in sorted(mods):
        e = sorted(a["edges"][name])
        ib = sorted(a["imported_by"][name])
        o.append("| `%s` | `%s` | %s | %s | %d |"
                 % (name, mods[name]["rel"],
                    ", ".join("`%s`" % x for x in e) or "—",
                    ", ".join("`%s`" % x for x in ib) or "**none**",
                    len(a["external"][name])))
    o.append("")

    # 5.3 ------------------------------------------------------------------
    o.append("### 5.3 Modules with NO STATIC REFERENCE FOUND")
    o.append("")
    o.append("Nothing in the tree imports these, and they are not test modules. **This is not "
             "a deletion list.** A module can be reached by a workflow entrypoint, by "
             "`python -m`, or by a name built at run time — none of which an AST sees. Read "
             "this beside §7.1's entrypoint column before concluding anything.")
    o.append("")
    if not a["unreferenced_modules"]:
        o.append("**None** — every non-test module is imported by at least one other.")
    else:
        o.append("| module | file | in §7.1's entrypoint column? |")
        o.append("|---|---|---|")
        for n in a["unreferenced_modules"]:
            o.append("| `%s` | `%s` | *check §7.1* |" % (n, mods[n]["rel"]))
    o.append("")

    # 5.4 ------------------------------------------------------------------
    o.append("### 5.4 Module-level symbols with NO STATIC REFERENCE FOUND ANYWHERE")
    o.append("")
    n_lonely = sum(len(v) for v in a["lonely"].values())
    n_internal = sum(len(v) for v in a["internal_only"].values())
    o.append("**%d of %d** module-level symbols (dunders excluded). A symbol here is defined "
             "at module level and its name is READ nowhere in the tree — not by another "
             "module and not by its own. This is the class that produced DET-DEAD and "
             "`_FORCE_PROVIDER`, five months apart, both found by accident."
             % (n_lonely, a["n_symbols"]))
    o.append("")
    o.append("A further **%d** are read only inside the module that defines them. Those are "
             "private helpers, not candidates, and are not listed. An earlier draft of this "
             "generator counted them here and the table came out at 27 of 31 rows — a true "
             "statement with no signal in it." % n_internal)
    o.append("")
    if not a["lonely"]:
        o.append("**None.**")
    else:
        o.append("| module | symbols |")
        o.append("|---|---|")
        for name in sorted(a["lonely"]):
            syms = a["lonely"][name]
            o.append("| `%s` | %s |" % (name, ", ".join("`%s`" % s for s in syms)))
    o.append("")

    # 5.5 ------------------------------------------------------------------
    o.append("### 5.5 Which modules a test module imports")
    o.append("")
    tests = sorted(n for n in mods if a["is_test"][n])
    non_test = [n for n in mods if not a["is_test"][n]]
    o.append("**%d test modules import %d of the %d non-test modules.** Coverage here means "
             "ONE THING ONLY: a test module names it in an import. It does not mean the "
             "module's behaviour is asserted, and it does not mean the test passes — "
             "36 assertions in `ai_engine/tests/` have never been run in CI (order item)."
             % (len(tests), len(a["covered"] & set(non_test)), len(non_test)))
    o.append("")
    o.append("| test module | imports |")
    o.append("|---|---|")
    for t in tests:
        e = sorted(a["edges"][t])
        o.append("| `%s` | %s |" % (t, ", ".join("`%s`" % x for x in e) or "—"))
    o.append("")
    uncovered = sorted(n for n in non_test if n not in a["covered"])
    o.append("**Imported by no test module (%d):** %s"
             % (len(uncovered), ", ".join("`%s`" % n for n in uncovered) or "none"))
    o.append("")

    # 5.6 ------------------------------------------------------------------
    o.append("### 5.6 What §5 does not answer")
    o.append("")
    o.append("- **Whether an import is CALLED.** This is a static reader. `imports X` is not "
             "`calls X at run time`; §6 holds the runtime side.")
    o.append("- **Dynamic reference.** `getattr`, a name assembled from a string, a plugin "
             "registry, an `__all__` re-export and a CLI entrypoint are all invisible here. "
             "Every column above therefore says NO STATIC REFERENCE FOUND and never `dead`.")
    o.append("- **Same-name collisions mask a lonely symbol.** 5.4 matches symbol names across "
             "the whole tree, so a symbol called `main` is never reported even when this "
             "module's `main` is unused. The failure direction is a FALSE NEGATIVE — the "
             "section under-reports rather than accusing live code — and that is deliberate.")
    o.append("- **Whether a workflow runs a module.** §7.1's entrypoint column. Joining the "
             "two tables is the reader's job and both halves stay true; this generator does "
             "not parse YAML.")
    o.append("- **pytest discovery.** `test_*` functions and `Test*` classes are found by "
             "NAME at run time, so 5.4 lists them as unreferenced. They are collected by the "
             "runner, not called by any module. Read that block with this in mind.")
    o.append("- **Untracked files.** The inventory is `git ls-files '*.py'`. A file that is "
             "not tracked is not architecture.")
    o.append("")
    return "\n".join(o)


def splice(src_text: str, section: str) -> str:
    lines = src_text.splitlines()
    start = end = None
    for i, ln in enumerate(lines):
        if start is None and ln.startswith("## §5"):
            start = i
        elif start is not None and ln.startswith("## §6"):
            end = i
            break
    if start is None or end is None:
        raise ValueError("could not locate the §5..§6 boundary in the source document")
    return "\n".join(lines[:start] + section.splitlines() + lines[end:]) + "\n"


# --------------------------------------------------------------------------- main

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument("--session", type=int, required=True,
                    help="session number; names the OUTPUT document. No default on purpose: "
                         "gni_state.py's default=94 writes S98 content under an S94 name "
                         "(item 5.34).")
    ap.add_argument("--src", default=None)
    ap.add_argument("--stdout", action="store_true")
    args = ap.parse_args(argv)

    fails, n_probe = control_probe()
    if fails:
        print("CONTROL PROBE FAILED -- nothing written. The instrument is wrong, "
              "not the repo:", file=sys.stderr)
        for f in fails:
            print("  - " + f, file=sys.stderr)
        return 2
    print("CONTROL PROBE: %d/%d pass (naming, aliases across path roots, BOM, sibling + "
          "function-level + bare-name edges, external negatives, ambiguity, sys.path sites, "
          "orphan module, package exclusion, lonely vs private symbols, EOL hashing)"
          % (n_probe, n_probe))

    try:
        snap = collect(ROOT)
        a = analyse(snap)
    except ValueError as exc:
        print("REFUSING: %s" % exc, file=sys.stderr)
        return 2
    section = render(snap, a)

    if args.stdout:
        print(section)
        return 0

    if args.src:
        src = Path(args.src)
    else:
        cands = sorted(DOCS.glob("GNI_ARCHITECTURE_S*.md"),
                       key=lambda p: int(re.sub(r"\D", "", p.stem) or 0))
        if not cands:
            print("MISSING: no GNI_ARCHITECTURE_S*.md under %s" % DOCS, file=sys.stderr)
            return 3
        src = cands[-1]
    if not src.is_file():
        print("MISSING: %s" % src, file=sys.stderr)
        return 3
    out = DOCS / ("GNI_ARCHITECTURE_S%d.md" % args.session)
    try:
        text = splice(src.read_text(encoding="utf-8"), section)
    except ValueError as exc:
        print("REFUSING: %s (source: %s)" % (exc, src), file=sys.stderr)
        return 2
    out.write_text(text, encoding="utf-8", newline="\n")
    print("SOURCE : %s" % src.name)
    print("WROTE  : %s  (%d bytes)" % (out.relative_to(ROOT), len(text)))
    print("§5 covers %d modules, %d internal edges, %d with no static reference, "
          "%d lonely symbols of %d"
          % (len(snap["modules"]), sum(len(v) for v in a["edges"].values()),
             len(a["unreferenced_modules"]),
             sum(len(v) for v in a["lonely"].values()), a["n_symbols"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
